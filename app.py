# Dividir datos en trozos (chunks)
from langchain_text_splitters import RecursiveCharacterTextSplitter
from langchain_core.documents import Document

porcionador = RecursiveCharacterTextSplitter(chunk_size=1000, chunk_overlap=100)
trozos = porcionador.split_documents(archivos)
print(f"Cantidad de trozos: {len(trozos)}")

# Agregamos los trozos a los documentos del asistente
documents = trozos
ids = [ str(i) for i in range( len(documents) ) ]

# Agregar archivos Excel, CSV
import pandas as pd

nombre_archivo = "./mis_archivos/Copia de Tabla productos.xlsx"
if nombre_archivo != "":
    tabla = pd.read_excel(nombre_archivo)

    id = len(ids)
    for i, fila in tabla.iterrows():

        # Configurar los nombres de las columnas
        doc = Document(
            page_content = f"""
                Nombre:             {fila['Nombre']}
                Categoría:          {fila['Categoría']}
                Calificación:       {fila['Calificación']}
                Unidades Vendidas:  {fila['Unidades Vendidas']}
                En Tendencia:       {fila['En Tendencia']}
                Valor (USD):        {fila['Valor (USD)']}
                Opiniones Buenas:   {fila['Opiniones Buenas']}
                Opiniones Malas:    {fila['Opiniones Malas']}
                """,

            # Configurar columnas con metadatos
            metadata = {
                "En Tendencia":     fila["En Tendencia"],
                "Opiniones Buenas": fila["Opiniones Buenas"],
                "Opiniones Malas":  fila["Opiniones Malas"]
            },
            id = str(id)
        )

        # Agregamos los documentos al asistente virtual
        documents.append(doc)
        ids.append(str(id))
        id += 1

