contexto = ''

def respuesta_ia(pregunta):
    global contexto
    respuesta = recuperador.invoke( pregunta )
    mostrar = cadena.invoke({
        'contexto': contexto,
        'pregunta': pregunta,
        'respuesta': respuesta
    })

    contexto += f"\nUsuario: {pregunta}\nBot: {respuesta}"
    return mostrar.content

